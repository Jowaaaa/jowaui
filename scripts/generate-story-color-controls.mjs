import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const componentsDir = join(root, "src", "lib", "components");
const outputPath = join(root, "src", "stories", "generated-component-colors.ts");

const COLOR_PROPERTIES = /(?:^|[;{}\n])\s*(color|background(?:-color)?|border(?:-[a-z]+)?|fill|stroke)\s*:\s*([^;{}]+)/gi;
const VARIABLE = /var\(\s*(--[a-z0-9-]+)/gi;

const humanize = (variable) => {
  const words = variable
    .replace(/^--jowa-/, "")
    .split("-")
    .filter(Boolean);
  return words
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
};

const keyFor = (variable) =>
  `cssColor${variable
    .replace(/^--/, "")
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("")}`;

const componentEntries = [];
const componentNames = (await readdir(componentsDir, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

for (const component of componentNames) {
  const cssPath = join(componentsDir, component, `${component}.css`);
  let css;
  try {
    css = await readFile(cssPath, "utf8");
  } catch {
    continue;
  }

  const variables = new Set();
  for (const match of css.matchAll(COLOR_PROPERTIES)) {
    const property = match[1].toLowerCase();
    if (property.includes("radius") || property.includes("width") || property.includes("style")) continue;
    for (const variable of match[2].matchAll(VARIABLE)) variables.add(variable[1]);
  }

  const controls = [...variables].sort().map((variable) => ({
    key: keyFor(variable),
    name: humanize(variable),
    variables: [variable],
    category: component.charAt(0).toUpperCase() + component.slice(1),
  }));

  componentEntries.push([component, controls]);
}

const body = componentEntries
  .map(([component, controls]) => `  ${JSON.stringify(component)}: ${JSON.stringify(controls)},`)
  .join("\n");

const source = `// Generated by scripts/generate-story-color-controls.mjs. Do not edit manually.\nimport type { ComponentColorControl } from "./component-colors";\n\nexport const GENERATED_COMPONENT_CONTROLS: Record<string, ComponentColorControl[]> = {\n${body}\n};\n`;

await writeFile(outputPath, source);
console.log(`Generated ${relative(root, outputPath)} for ${componentEntries.length} components.`);
